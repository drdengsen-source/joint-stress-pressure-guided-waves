"""Reproduce Fig. 4(c) and 4(d) of the manuscript from the transducer design data.

Usage:  python plot_fig4cd.py [csv] [out_prefix]
        csv defaults to ./data/E4_paperfig_data.csv; out_prefix to ./fig4cd_reproduced

Input columns (D1T stack: three radially magnetized rings, +-+, pitch 10.4 mm, evaluated on the
pipe outer wall r = 6.5 mm; generated by matlab/E1_force_field.m -> E2_coil_spectrum.m -> E4_paperfig_data.m):
  z_mm        axial position (mm)
  Br_T, Bz_T  static flux density components (T)
  fz_wall     axial force line density of the wall-mode coil set per unit current (N m^-1 A^-1)
  fr_liq      radial force line density of the liquid-mode coil set per unit current
  fr_wall_x   radial (cross) component of the wall-mode set
  fz_liq_x    axial (cross) component of the liquid-mode set
Spatial spectrum: F(lambda) = | integral f(z) exp(-i 2 pi z / lambda) dz |  (N/A).
Requires numpy, matplotlib.
"""
import os
import sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "data", "E4_paperfig_data.csv")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "fig4cd_reproduced")
_trapz = getattr(np, "trapezoid", None) or np.trapz   # numpy >= 2.0 renamed trapz
LAM_W = 10.4                       # mm, wall-borne wavelength at 520 kHz
BAND = (4.79, 7.07)                # mm, wavelengths of the three liquid-borne branches at 280 kHz

d = np.genfromtxt(CSV, delimiter=",", names=True)
z = d["z_mm"] * 1e-3


def spectrum(f, lam_mm):
    lam = np.asarray(lam_mm) * 1e-3
    ph = np.exp(-2j * np.pi * z[None, :] / lam[:, None])
    return np.abs(_trapz(f[None, :] * ph, z, axis=1))


lam = np.linspace(2, 30, 1401)
S = {k: spectrum(d[k], lam) for k in ["fz_wall", "fr_wall_x", "fr_liq", "fz_liq_x"]}
print("F_z,wall(lambda_w = 10.4 mm) = %.3f N/A" % spectrum(d["fz_wall"], [LAM_W])[0])
print("F_r,liq(5.2 mm)              = %.3f N/A" % spectrum(d["fr_liq"], [5.2])[0])
print("F_r,liq(6.3 / 4.5 mm)        = %.3f / %.3f N/A" % tuple(spectrum(d["fr_liq"], [6.3, 4.5])))
print("F_r,wall cross(10.4 mm)      = %.3f N/A" % spectrum(d["fr_wall_x"], [LAM_W])[0])
print("peak |B| on the wall         = %.2f T" % np.max(np.hypot(d["Br_T"], d["Bz_T"])))

plt.rcParams.update({"font.family": "STIXGeneral", "mathtext.fontset": "stix", "font.size": 9})
ORANGE, BLUE = "#D55E00", "#0072B2"
fig, (a, b) = plt.subplots(2, 1, figsize=(3.6, 4.6), gridspec_kw=dict(hspace=0.45, left=0.17,
                                                                      right=0.97, top=0.95, bottom=0.1))
a.plot(d["z_mm"], d["fz_wall"], color=ORANGE, lw=1.4, label=r"$f_z$, wall set")
a.plot(d["z_mm"], d["fr_liq"], color=BLUE, lw=1.4, ls="-.", label=r"$f_r$, liquid set")
a.axhline(0, color="0.7", lw=0.6)
a.set(xlim=(-20, 20), xlabel=r"$z$ (mm)", ylabel=r"$f$ (N m$^{-1}$ A$^{-1}$)")
a.legend(frameon=False, fontsize=8, loc="upper left")
a.text(-0.16, 1.02, "(c)", transform=a.transAxes, fontweight="bold")

b.axvspan(*BAND, color=BLUE, alpha=0.12, lw=0)
for x in (LAM_W / 2, LAM_W):
    b.axvline(x, color="0.5", ls=":", lw=0.8)
b.plot(lam, S["fz_wall"], color=ORANGE, lw=1.4, label=r"$F_z$, wall")
b.plot(lam, S["fr_wall_x"], color=ORANGE, lw=1.0, ls=":", label=r"$F_r$, wall (cross)")
b.plot(lam, S["fr_liq"], color=BLUE, lw=1.4, ls="-.", label=r"$F_r$, liquid")
b.plot(lam, S["fz_liq_x"], color=BLUE, lw=1.0, ls="--", label=r"$F_z$, liquid (cross)")
b.set(xlim=(2, 30), ylim=(0, 1.4), xlabel=r"$\lambda$ (mm)", ylabel=r"$|F(\lambda)|$ (N A$^{-1}$)")
b.legend(frameon=False, fontsize=7.5, loc="upper right")
b.text(-0.16, 1.02, "(d)", transform=b.transAxes, fontweight="bold")

fig.savefig(OUT + ".png", dpi=600)
fig.savefig(OUT + ".pdf")
print("saved", OUT + ".png", OUT + ".pdf")
